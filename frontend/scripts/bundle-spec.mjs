/*
Bundle openapi/ into the single openapi.yaml both generators read.

The spec is authored as a tree — openapi/openapi.yaml holds the index, and the
paths and schemas live in per-domain files beside it — because one 4,600-line
YAML is the file two branches are most likely to edit at once, and a conflict in
it is unpleasant in a way a conflict in Go is not (#114).

Neither generator can read that tree directly. openapi-typescript resolves
external $refs happily; oapi-codegen does not — it treats an external reference
as "this type is generated into another Go package", so it either refuses
outright or emits `type Health = Health` and drops the definition. There is no
flatten flag. So the tree is bundled back into one document first, and the
generators go on reading exactly what they read before.

Deliberately json-schema-ref-parser rather than a full OpenAPI toolchain:
@redocly/cli does the same job, and brings OpenTelemetry, react-router and three
critical advisories with it to concatenate some YAML. This adds 33 lines to the
lockfile and no advisories at all.

The check that this is honest is not in here — it is that `make generate`
produces byte-identical api.gen.go and schema.d.ts, which CI runs on every
change. A bundler that quietly dropped or reordered something would move them.
*/
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import $RefParser from "@apidevtools/json-schema-ref-parser";
import { dump } from "js-yaml";

const src = fileURLToPath(new URL("../../openapi/openapi.yaml", import.meta.url));
const out = fileURLToPath(new URL("../../openapi.yaml", import.meta.url));

const bundled = await $RefParser.bundle(src);

writeFileSync(
  out,
  "# GENERATED by npm run gen:bundle — edit openapi/ instead, then `make generate`.\n" +
    dump(bundled, { lineWidth: -1, noRefs: true, quoteStyle: "double" }),
);
console.log(`bundled openapi/ → openapi.yaml`);
